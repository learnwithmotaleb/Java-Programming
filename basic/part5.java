public class part5 {
     public static void main(String[] args) {
          //assignment operator
          //=, +=, -=, *=, /=, %=
          //x += 5 , x = x+5;

          int x = 3;
          int y = 2;

          x += y; //x = x + y
          System.out.println("x = "+ x);

          x -= y; //x = x - y
          System.out.println("x = "+ x);

          x *= y; //x = x * y
          System.out.println("x = "+ x);

          x /= y; //x = x / y
          System.out.println("x = "+ x);

          x %= y; //x = x % y
          System.out.println("x = "+ x);

        


     }
}
