public class part17 {
     public static void main(String[] args) {
          //bitwise operator
          //

          int a = 32;
          int b = 12;
          int c;

          c = a & b;
          System.out.println(c);

      
          c = a | b;
          System.out.println(c);


       
          c = a ^ b;
          System.out.println(c);

          c = a >> 3; //right shift
          System.out.println(c);

          c = a << 2; //left shift
          System.out.println(c);



     }
}
