public class part18 {
     public static void main(String[] args) {
          // looping
          // for, while, do-while looping
          // for
          for (int i = 1; i < 10; i++) {
               System.out.println("Hello, Motaleb item- : " + i);
          }
          System.out.println("\n");

          // while
          int x = 0;
          while (x < 10) {
               System.out.println("Hello, Bangladesh cout " + x);

               x++;

          }
          System.out.println();
          System.out.println();

          // do while
          int y = 0;
          do { 
               y++;
               System.out.println("Hello, Motaleb "+ y);

             
          } while (y < 10);
     }
}
