public class part19 {
     public static void main(String[] args) {
          
          //while and do while main defference

          int x = 6;
          while(x<=5){
               System.out.println("Bangladesh");
               x++;
          }
          

          int i = 6;
          do{
               System.out.println("Bangladesh");
               i++;
          }while(i<=5);
     }
}
